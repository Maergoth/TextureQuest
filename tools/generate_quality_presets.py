"""Generate the renderer's typed preset visitor from the launcher's shared contract."""
from pathlib import Path
import argparse
import json
import math

ROOT = Path(__file__).resolve().parents[1]


def render(contract):
    if contract.get('schema') != 'texturequest-quality-presets-v1':
        raise ValueError('Unsupported quality preset contract')
    rows = contract['presets']
    if [row['name'] for row in rows] != ['Low', 'Medium', 'High', 'Max']:
        raise ValueError('Quality preset order changed')
    keys = None
    lines = ['#pragma once', '// Generated by tools/generate_quality_presets.py; edit src/quality-presets.json.',
             'namespace tq_quality {', 'inline constexpr unsigned Count = 4;',
             'inline constexpr const char *Names[] = { "Low", "Medium", "High", "Max" };',
             'template<class Visitor> bool VisitSettings(unsigned index, Visitor visit) {', '    switch (index) {']
    for index, row in enumerate(rows):
        if set(row['settings']) != {'EQ2Graphics'}:
            raise ValueError('Presets must only own world graphics settings')
        settings = row['settings']['EQ2Graphics']
        if keys is None:
            keys = set(settings)
        if set(settings) != keys:
            raise ValueError('Every preset must cover the same settings')
        lines.append(f'    case {index}:')
        for key, value in settings.items():
            if not key.isascii() or not key.isalnum():
                raise ValueError('Invalid setting key')
            if type(value) is bool:
                literal = 'true' if value else 'false'
            elif type(value) is int:
                literal = str(value)
            elif type(value) is float and math.isfinite(value):
                literal = repr(value) + 'f'
            else:
                raise ValueError('Preset values must be finite typed scalars')
            lines.append(f'        visit("{key}", {literal});')
        lines.append('        return true;')
    lines += ['    default: return false;', '    }', '}', '} // namespace tq_quality', '']
    return '\n'.join(lines).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(json.loads((ROOT / 'src/quality-presets.json').read_bytes()))
    target = ROOT / 'graphics-renderer/quality_presets.hpp'
    if args.check:
        if not target.is_file() or target.read_bytes() != expected:
            raise SystemExit('Quality preset header differs; regenerate before building')
    else:
        target.write_bytes(expected)


if __name__ == '__main__':
    main()
